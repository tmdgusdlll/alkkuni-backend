-- 브랜드 사전: 제품명 앞부분의 표기 → 대표 브랜드. 식약처 데이터에는 판매사(브랜드) 칸이 없고 BSSH_NM은 위탁생산 제조사라 제품명에서 뽑는다.
-- 초기 데이터는 로컬 적재(2026-11-11) 소비자용 제품명의 첫 단어 후보를 사람이 검토한 것이다. 검토 표(근거 URL 포함)는 docs/brand-dictionary.csv.
-- 사전을 고친 뒤에는 batch의 alkkuni.job=link-brands로 기존 제품을 다시 연결한다(식약처 API 호출 없음).
-- 운영사(예: 여에스더·닥터에스더 → 에스더포뮬러)와 제품별 수동 지정은 아직 두지 않는다.

CREATE TABLE brand (
    id   BIGSERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

-- whole_word: 제품명 첫 단어가 표기와 같을 때만 연결한다. 붙여 쓴 이름에서 다른 이름과 앞부분이 겹치는 표기다(예: 필리 → 필리브).
-- brand_id가 NULL이면 검토에서 보류한 표기다. 가장 긴 표기가 먼저 맞으므로 더 짧은 표기로 잘못 연결되는 것을 막는다
-- (예: 보류한 "유한M"이 없으면 "유한M 비타민D"가 "유한" → 유한양행으로 연결된다). 판매원을 확인하면 brand_id만 채운다.
CREATE TABLE brand_alias (
    alias_key  VARCHAR(100) PRIMARY KEY,                     -- BrandName.key 결과
    brand_id   BIGINT       REFERENCES brand (id),
    whole_word BOOLEAN      NOT NULL
);

ALTER TABLE product ADD COLUMN brand_id BIGINT REFERENCES brand (id);
-- 브랜드 필터·브랜드별 제품 수에 쓴다. 대부분(약 88%)이 NULL이라 부분 인덱스로 둔다.
CREATE INDEX idx_product_brand_id ON product (brand_id) WHERE brand_id IS NOT NULL;

