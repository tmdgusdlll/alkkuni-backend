package com.alkkuni.core.product.enums

// 기준규격 분모(표시량의 "/2,400mg")가 하루 섭취량인지 섭취방법으로 확인한 결과.
// 함량 행이 없는 제품은 확인할 분모가 없어 null이다.
enum class BasisCheck {
    // 1일 횟수 × 1회 중량 = 분모. 함량이 곧 1일 함량이다.
    DAILY,
    // 1회 중량 = 분모(1일 2회 이상). 1일 함량 = 함량 × 1일 횟수.
    PER_SERVING,
    // 비교할 수 있었는데 하루치도 1회분도 아니다("4mg/g"처럼 단위당 표기 포함).
    MISMATCH,
    // 섭취방법은 읽었지만 비교할 수 없다. 1회 중량이 없거나, 무게·부피가 섞였거나, 분모가 여러 개다.
    UNVERIFIED,
    // 섭취방법을 읽지 못했다(없음, 범위·선택 표기, 원료용 문구 등).
    UNREADABLE,
}
